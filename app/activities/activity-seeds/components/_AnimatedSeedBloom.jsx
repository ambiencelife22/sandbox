const AnimatedSeed = ({ isActive }) => {
  const [currentSVG, setCurrentSVG] = useState(0)
  const svgList = [<SeedPlanted key="planted" />, <SeedSprout key="sprout" />, <SeedBloom key="bloom" />]
  const sounds = activitySoundManager()

  useEffect(() => {
    if (isActive) {
      sounds.correctDropletBubbleSound.toggle()
    }
  }, [isActive])

  useEffect(() => {
    if (isActive) {
      const delay = currentSVG === 2 ? bloomDuration : phaseDuration
      const timer = setTimeout(() => {
        setCurrentSVG((currentSVG + 1) % totalPhases)
      }, delay)

      return () => clearTimeout(timer) 
    }
  }, [currentSVG, isActive])

  if (!isActive) {
    return null
  }

  return <div className='animated_seed_img'>{svgList[currentSVG]}</div>
}

export default AnimatedSeed